import { CoffeeProduct } from '@/src/types/types';

export const createGenerateQuestionsPrompt = (products: CoffeeProduct[]): string => `
あなたはコーヒーの専門家であり、質問の達人です。以下のコーヒー商品データと条件を基に、初心者が好みの豆にたどり着くための質問フローを作成してください。

条件：
1. 質問フローの基本構造
- 質問は最大で4つまでとすること
- 各質問の選択肢は2-3個程度とすること
- 必ず最後の選択肢で商品の推薦に到達すること（途中で終わらないこと）
- 質問は日本語で作成すること

2. 質問の内容と表現
- 質問は初心者にもわかりやすい表現を使用すること
- 専門用語を使用する場合は、括弧内に簡単な説明を加えること
- 質問は相手の好みを尋ねる内容に限定すること（例：「どのような風味がお好みですか？」）
- 選択肢は明確に異なる特徴を持つこと

3. 商品のカバレッジ
- 提供された商品リストの全ての商品が、少なくとも1つの選択肢の結果として推薦されること
- 各商品の特徴（焙煎度、風味ノート、特徴）を考慮して適切な質問フローを設計すること
- 商品が推薦される可能性が均等になるように選択肢を設計すること

4. 検証手順
以下の項目を必ずチェックしてください：
- [ ] 全ての質問パスが商品推薦で終わっているか
- [ ] 全ての商品が少なくとも1つの推薦パスに含まれているか
- [ ] 選択肢が互いに排他的で明確か
- [ ] 質問と選択肢が初心者にわかりやすい表現になっているか
- [ ] 専門用語に説明が付いているか

以下の形式のJSONで返してください:
[
  {
    "id": "Q1",
    "question": "質問文",
    "options": [
      { "text": "選択肢1", "nextQuestion": "Q2" },
      { "text": "選択肢2", "nextQuestion": "Q3" }
    ]
  },
  {
    "id": "Q2",
    "question": "質問文",
    "options": [
      { 
        "text": "選択肢1",
        "result": ["商品名1", "商品名2"]
      },
      {
        "text": "選択肢2",
        "result": ["商品名3", "商品名4"]
      }
    ]
  }
]

商品リスト：
${JSON.stringify(products, null, 2)}

注意：
- 返答は必ずJSONのみとし、説明などは含めないでください
- 全ての質問パスが必ず商品推薦で終わるようにしてください
- 全ての商品が少なくとも1つの推薦パスに含まれるようにしてください
`; 