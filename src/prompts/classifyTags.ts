export const createTagClassificationPrompt = (tag: string): string => `
あなたはコーヒーに関する専門的な知識を持つAIアシスタントです。
以下のタグを厳密に分類してください。

対象タグ: ${tag}

【分類カテゴリ】
1. 焙煎度
2. 風味
3. 特徴

【各カテゴリの定義】

1. 焙煎度に関するタグ:
   - 焙煎の度合いを直接的に表現するもの
   - 例: Lv1-8、浅煎り、中煎り、深煎り、ライトロースト、シティーロースト等

2. 風味に関するタグ:
   a) 基本風味
      - 五味（甘味、酸味、苦味、塩味、うま味）
      - 味わいの質感（コク、まろやか、すっきり等）
      - 香りの特徴（香ばしい、華やか等）
   
   b) 具体的な風味
      - 果実系（柑橘、ベリー、トロピカルフルーツ等）
      - 花・ハーブ系（フローラル、ジャスミン、ハーブ等）
      - ナッツ・チョコレート系
      - その他（キャラメル、蜂蜜等）
   
   c) 風味の特徴を表す表現
      - 強さ（強い、控えめ等）
      - 質（クリーン、複雑等）
      - 時間的変化（余韻、後味等）

3. 特徴に関するタグ:
   a) 栽培・生産に関する特徴
      - 精製方法（ウォッシュド、ナチュラル等）
      - 栽培方法（シェードグロウン、有機栽培等）
      - 認証（オーガニック、スペシャルティ等）
   
   b) 豆の特徴
      - 品種（ゲイシャ、ブルボン等）
      - 等級（AA、SHB、G1等）
      - 産地特性（標高、土壌等）

【判定ルール】
1. 一つのタグは必ず1つのカテゴリーにのみ分類する
2. 複数の要素を含むタグの場合、主たる要素で判断する
3. 風味に関する表現は、たとえ特徴を説明する文脈でも「風味」カテゴリに分類する
4. 判断に迷う場合は以下の優先順位で判断する：
   焙煎度 > 風味 > 特徴

以下の形式でJSONを返してください：
{
  "category": "焙煎度" | "風味" | "特徴",
  "explanation": "分類理由の簡潔な説明"
}
`; 